drop function if exists public.get_course_reaction_counts(bigint[]);
drop function if exists public.get_course_reaction_counts(bigint[],text);
create or replace function public.get_course_reaction_counts(course_ids bigint[], p_session_id text)
returns table(course_id bigint, likes bigint, dislikes bigint, user_reaction text)
language sql
security definer
set search_path = public
as $$
  select t.course_id,
         t.likes,
         t.dislikes,
         (select r.reaction from public.course_reactions r where r.course_id=t.course_id and r.session_id=p_session_id)
  from public.course_reaction_totals t
  where t.course_id = any(course_ids)
  order by t.course_id;
$$;

grant execute on function public.get_course_reaction_counts(bigint[], text) to anon;

create or replace function public.set_course_reaction(
  p_course_id bigint,
  p_session_id text,
  p_reaction text
)
returns table(course_id bigint, likes bigint, dislikes bigint, user_reaction text)
language plpgsql
security definer
set search_path = public
as $$
declare
  old_reaction text;
  new_likes bigint;
  new_dislikes bigint;
begin
  if p_reaction not in ('like','dislike') then raise exception 'invalid reaction'; end if;
  if length(p_session_id) < 12 or length(p_session_id) > 120 then raise exception 'invalid session'; end if;
  if not exists (select 1 from public.course_catalogue where id=p_course_id) then raise exception 'course not found'; end if;

  select reaction into old_reaction
  from public.course_reactions
  where course_id=p_course_id and session_id=p_session_id;

  if old_reaction = p_reaction then
    delete from public.course_reactions where course_id=p_course_id and session_id=p_session_id;
    update public.course_reaction_totals
      set likes = case when p_reaction='like' then greatest(likes-1,0) else likes end,
          dislikes = case when p_reaction='dislike' then greatest(dislikes-1,0) else dislikes end,
          updated_at=now()
      where course_id=p_course_id;
  else
    insert into public.course_reactions(course_id,session_id,reaction,updated_at)
    values(p_course_id,p_session_id,p_reaction,now())
    on conflict(course_id,session_id)
    do update set reaction=excluded.reaction,updated_at=now();

    update public.course_reaction_totals
      set likes = greatest(likes
          + case when p_reaction='like' then 1 else 0 end
          - case when old_reaction='like' then 1 else 0 end,0),
          dislikes = greatest(dislikes
          + case when p_reaction='dislike' then 1 else 0 end
          - case when old_reaction='dislike' then 1 else 0 end,0),
          updated_at=now()
      where course_id=p_course_id;
  end if;

  select likes,dislikes into new_likes,new_dislikes
  from public.course_reaction_totals
  where course_id=p_course_id;

  return query select p_course_id,new_likes,new_dislikes,
    (select r.reaction from public.course_reactions r where r.course_id=p_course_id and r.session_id=p_session_id);
end;
$$;

grant execute on function public.set_course_reaction(bigint,text,text) to anon;

