-- Sayeed Courses live backend foundation v2
-- Idempotent: safe to re-run after the first setup.

create table if not exists public.course_catalogue (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  educator text,
  price numeric(10,2) default 0,
  thumbnail_url text,
  telegram_url text,
  initial_likes bigint not null default 0,
  initial_dislikes bigint not null default 0,
  created_at timestamptz default now()
);

create table if not exists public.course_reactions (
  course_id bigint not null references public.course_catalogue(id) on delete cascade,
  session_id text not null,
  reaction text not null check (reaction in ('like','dislike')),
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (course_id, session_id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  type text default 'info',
  created_at timestamptz default now()
);

create table if not exists public.course_reaction_totals (
  course_id bigint primary key references public.course_catalogue(id) on delete cascade,
  likes bigint not null default 0,
  dislikes bigint not null default 0,
  updated_at timestamptz default now()
);

alter table public.course_catalogue enable row level security;
alter table public.course_reactions enable row level security;
alter table public.notifications enable row level security;
alter table public.course_reaction_totals enable row level security;

drop policy if exists "public read course catalogue" on public.course_catalogue;
create policy "public read course catalogue" on public.course_catalogue for select to anon using (true);

drop policy if exists "public read notifications" on public.notifications;
create policy "public read notifications" on public.notifications for select to anon using (true);

drop policy if exists "public read reaction totals" on public.course_reaction_totals;
create policy "public read reaction totals" on public.course_reaction_totals for select to anon using (true);

