-- Backfill totals only for courses that don't have a totals row yet.
insert into public.course_reaction_totals(course_id,likes,dislikes)
select c.id,
       c.initial_likes + count(*) filter (where r.reaction='like'),
       c.initial_dislikes + count(*) filter (where r.reaction='dislike')
from public.course_catalogue c
left join public.course_reactions r on r.course_id=c.id
where not exists (select 1 from public.course_reaction_totals t where t.course_id=c.id)
group by c.id,c.initial_likes,c.initial_dislikes;

create or replace function public.ensure_course_reaction_total()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.course_reaction_totals(course_id,likes,dislikes)
  values (new.id,new.initial_likes,new.initial_dislikes)
  on conflict (course_id) do nothing;
  return new;
end;
$$;

drop trigger if exists trg_course_reaction_total on public.course_catalogue;
create trigger trg_course_reaction_total
after insert on public.course_catalogue
for each row execute function public.ensure_course_reaction_total();

