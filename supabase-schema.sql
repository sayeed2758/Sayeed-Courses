-- Sayeed Courses — live catalogue, reactions, notifications and coupons.
-- Run this entire file in Supabase SQL Editor.
-- Safe to run again: additive changes + create-or-replace/drop patterns are used.

create table if not exists public.course_catalogue (
  id bigint generated by default as identity primary key,
  number integer,
  title text not null,
  category text not null,
  educator text,
  price numeric(10,2) default 0,
  rating numeric(3,2) default 4.50,
  reviews bigint not null default 0,
  thumbnail_url text,
  telegram_url text,
  initial_likes bigint not null default 0,
  initial_dislikes bigint not null default 0,
  is_active boolean not null default true,
  created_at timestamptz default now()
);

alter table public.course_catalogue add column if not exists number integer;
alter table public.course_catalogue add column if not exists rating numeric(3,2) default 4.50;
alter table public.course_catalogue add column if not exists reviews bigint not null default 0;
alter table public.course_catalogue add column if not exists is_active boolean not null default true;

update public.course_catalogue
set number = id::integer
where number is null;

create unique index if not exists course_catalogue_number_uidx on public.course_catalogue(number);

create table if not exists public.course_reactions (
  course_id bigint not null references public.course_catalogue(id) on delete cascade,
  session_id text not null,
  reaction text not null check (reaction in ('like','dislike')),
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (course_id, session_id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  type text default 'info',
  created_at timestamptz default now()
);

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_percent numeric(5,2) not null check (discount_percent > 0 and discount_percent <= 100),
  starts_at timestamptz default now(),
  expires_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.course_catalogue enable row level security;
alter table public.course_reactions enable row level security;
alter table public.notifications enable row level security;
alter table public.coupons enable row level security;

drop policy if exists "public read course catalogue" on public.course_catalogue;
create policy "public read course catalogue" on public.course_catalogue for select to anon using (is_active = true);

drop policy if exists "public read notifications" on public.notifications;
create policy "public read notifications" on public.notifications for select to anon using (true);

