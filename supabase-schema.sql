drop function if exists public.get_course_count();
create or replace function public.get_course_count()
returns bigint
language sql
security definer
set search_path = public
as $$ select count(*) from public.course_catalogue where is_active = true; $$;
grant execute on function public.get_course_count() to anon;

drop function if exists public.get_course_reaction_counts(bigint[]);
drop function if exists public.get_course_reaction_counts(bigint[], text);
create or replace function public.get_course_reaction_counts(course_ids bigint[], p_session_id text default null)
returns table(course_id bigint, likes bigint, dislikes bigint, user_reaction text)
language sql
security definer
set search_path = public
as $$
  select ids.course_id,
         (coalesce(max(c.initial_likes),0) + coalesce(sum(case when r.reaction = 'like' then 1 else 0 end),0))::bigint,
         (coalesce(max(c.initial_dislikes),0) + coalesce(sum(case when r.reaction = 'dislike' then 1 else 0 end),0))::bigint,
         (select cr.reaction from public.course_reactions cr where cr.course_id = ids.course_id and cr.session_id = p_session_id limit 1)
  from unnest(course_ids) as ids(course_id)
  left join public.course_catalogue c on c.id = ids.course_id
  left join public.course_reactions r on r.course_id = ids.course_id
  group by ids.course_id
  order by ids.course_id;
$$;
grant execute on function public.get_course_reaction_counts(bigint[], text) to anon;

create or replace function public.set_course_reaction(
  p_course_id bigint,
  p_session_id text,
  p_reaction text
)
returns table(course_id bigint, likes bigint, dislikes bigint, user_reaction text)
language plpgsql
security definer
set search_path = public
as $$
declare old_reaction text;
begin
  if p_reaction not in ('like','dislike') then raise exception 'invalid reaction'; end if;
  if length(p_session_id) < 12 or length(p_session_id) > 120 then raise exception 'invalid session'; end if;

  select reaction into old_reaction from public.course_reactions where course_id = p_course_id and session_id = p_session_id;
  if old_reaction = p_reaction then
    delete from public.course_reactions where course_id = p_course_id and session_id = p_session_id;
  else
    insert into public.course_reactions(course_id, session_id, reaction, updated_at)
    values (p_course_id, p_session_id, p_reaction, now())
    on conflict (course_id, session_id) do update set reaction = excluded.reaction, updated_at = now();
  end if;

  return query
  select p_course_id,
         (coalesce(c.initial_likes,0) + coalesce((select count(*) from public.course_reactions where course_id=p_course_id and reaction='like'),0))::bigint,
         (coalesce(c.initial_dislikes,0) + coalesce((select count(*) from public.course_reactions where course_id=p_course_id and reaction='dislike'),0))::bigint,
         (select reaction from public.course_reactions where course_id=p_course_id and session_id=p_session_id)
  from public.course_catalogue c where c.id=p_course_id;
end;
$$;
grant execute on function public.set_course_reaction(bigint, text, text) to anon;

create or replace function public.validate_coupon(p_code text, p_subtotal numeric)
returns table(status text, message text, discount_percent numeric, discount_amount numeric, total numeric, code text)
language plpgsql
security definer
set search_path = public
as $$
declare c public.coupons%rowtype;
declare clean_code text;
BEGIN
  clean_code := upper(trim(coalesce(p_code,'')));
  select * into c from public.coupons where upper(code) = clean_code limit 1;

  if c.id is null or c.is_active = false then
    return query select 'not_valid'::text, 'Coupon not valid'::text, 0::numeric, 0::numeric, greatest(coalesce(p_subtotal,0),0)::numeric, clean_code;
    return;
  end if;

  if c.starts_at is not null and now() < c.starts_at then
    return query select 'not_valid'::text, 'Coupon not active yet'::text, 0::numeric, 0::numeric, greatest(coalesce(p_subtotal,0),0)::numeric, clean_code;
    return;
  end if;

  if c.expires_at is not null and now() > c.expires_at then
    return query select 'expired'::text, 'Coupon expired'::text, c.discount_percent, 0::numeric, greatest(coalesce(p_subtotal,0),0)::numeric, upper(c.code);
    return;
  end if;

  return query select 'valid'::text,
    'Coupon applied'::text,
    c.discount_percent,
    round((greatest(coalesce(p_subtotal,0),0) * c.discount_percent / 100.0), 2),
    round(greatest(coalesce(p_subtotal,0),0) - (greatest(coalesce(p_subtotal,0),0) * c.discount_percent / 100.0), 2),
    upper(c.code);
END;
$$;
grant execute on function public.validate_coupon(text, numeric) to anon;

