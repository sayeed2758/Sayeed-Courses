-- ================= ADMIN PHASE EXTENSION =================
-- Admin/security + catalogue management extension for Sayeed Courses.
-- Run AFTER the existing supabase-schema.sql.

alter table public.course_catalogue add column if not exists rating numeric(2,1) not null default 4.5 check (rating >= 4 and rating <= 5);
alter table public.course_catalogue add column if not exists review_count bigint not null default 0;
alter table public.course_catalogue add column if not exists is_published boolean not null default true;
alter table public.course_catalogue add column if not exists updated_at timestamptz not null default now();

alter table public.notifications add column if not exists is_published boolean not null default true;
alter table public.notifications add column if not exists updated_at timestamptz not null default now();

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  role text not null default 'admin' check (role in ('admin','super_admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_percent integer not null check (discount_percent between 1 and 100),
  expires_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  entity text not null,
  entity_id bigint,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
alter table public.coupons enable row level security;
alter table public.admin_audit_log enable row level security;

-- Public users never get direct coupon/admin/audit access. Server admin routes use the secret key.
drop policy if exists "admin self read" on public.admin_users;
create policy "admin self read" on public.admin_users for select to authenticated using (user_id = auth.uid());

-- Tighten public reads to published content.
drop policy if exists "public read course catalogue" on public.course_catalogue;
create policy "public read course catalogue" on public.course_catalogue for select to anon using (is_published = true);

drop policy if exists "public read notifications" on public.notifications;
create policy "public read notifications" on public.notifications for select to anon using (is_published = true);

-- Keep admin catalogue mutation out of browser roles; server admin APIs use the secret key.
revoke insert, update, delete on public.course_catalogue from anon, authenticated;
revoke insert, update, delete on public.notifications from anon, authenticated;
revoke select, insert, update, delete on public.coupons from anon, authenticated;
revoke select, insert, update, delete on public.admin_audit_log from anon, authenticated;

